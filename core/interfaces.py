"""Protocol definitions for repositories and services.

These protocols let the UI and business logic depend on abstractions instead of
concrete SQLite-backed implementations, which makes unit testing possible without
a real database or a running Qt application.
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from models.category import Category
from models.document import Document
from models.export_record import ExportRecord
from models.page_item import PageItem
from models.page_label import PageLabel
from models.pdf_page import PdfPage
from models.project import Project


# ------------------------------------------------------------------- repositories


@runtime_checkable
class ProjectRepository(Protocol):
    """Read/write access to the ``projects`` table."""

    def insert(self, project: Project) -> Project: ...
    def update(self, project: Project) -> None: ...
    def save(self, project: Project) -> None: ...
    def get(self, project_id: str) -> Project | None: ...
    def first(self) -> Project | None: ...
    def touch(self, project_id: str) -> None: ...
    def delete(self, project_id: str) -> None: ...


@runtime_checkable
class CategoryRepository(Protocol):
    """Read/write access to the ``categories`` table."""

    def list_for_project(self, project_id: str) -> list[Category]: ...
    def insert(self, category: Category) -> Category: ...
    def update(self, category: Category) -> None: ...
    def delete(self, category_id: str) -> None: ...


@runtime_checkable
class DocumentRepository(Protocol):
    """Read/write access to the ``documents`` table."""

    def list_for_project(
        self, project_id: str, in_library: bool | None = None
    ) -> list[Document]: ...
    def set_in_library(self, document_ids: list[str], in_library: bool) -> None: ...
    def get(self, document_id: str) -> Document | None: ...
    def find_by_hash(self, project_id: str, file_hash: str) -> list[Document]: ...
    def existing_hashes(self, project_id: str) -> dict[str, list[str]]: ...
    def insert_many(self, documents: list[Document]) -> None: ...
    def update(self, document: Document) -> None: ...
    def set_category(self, document_id: str, category_id: str | None) -> None: ...
    def set_categories(
        self, document_ids: list[str], category_id: str | None
    ) -> None: ...
    def set_sort_orders(self, ordered_ids: list[str]) -> None: ...
    def delete(self, document_id: str) -> None: ...
    def thumbnail_paths(self, document_ids: list[str]) -> list[str]: ...
    def thumbnail_in_use(self, path: str, project_id: str) -> bool: ...
    def counts_by_category(self, project_id: str) -> dict[str | None, int]: ...
    def count(self, project_id: str, in_library: bool | None = None) -> int: ...


@runtime_checkable
class PageRepository(Protocol):
    """Read/write access to the ``pdf_pages`` table."""

    def list_for_project(self, project_id: str) -> list[PdfPage]: ...
    def get(self, page_id: str) -> PdfPage | None: ...
    def count(self, project_id: str) -> int: ...
    def next_page_number(self, project_id: str) -> int: ...
    def insert(self, page: PdfPage) -> PdfPage: ...
    def update(self, page: PdfPage) -> None: ...
    def delete(self, page_id: str) -> None: ...
    def delete_all(self, project_id: str) -> None: ...
    def resequence(self, project_id: str, ordered_ids: list[str]) -> None: ...


@runtime_checkable
class PageItemRepository(Protocol):
    """Read/write access to the ``page_items`` table."""

    def list_for_page(self, page_id: str) -> list[PageItem]: ...
    def list_for_project(self, project_id: str) -> list[PageItem]: ...
    def get(self, item_id: str) -> PageItem | None: ...
    def count_for_page(self, page_id: str) -> int: ...
    def counts_by_page(self, project_id: str) -> dict[str, int]: ...
    def max_z_index(self, page_id: str) -> int: ...
    def insert(self, item: PageItem) -> PageItem: ...
    def update(self, item: PageItem) -> None: ...
    def update_many(self, items: list[PageItem]) -> None: ...
    def delete(self, item_id: str) -> None: ...
    def delete_for_page(self, page_id: str) -> None: ...
    def delete_for_project(self, project_id: str) -> None: ...
    def set_z_orders(self, ordered_ids: list[str]) -> None: ...


@runtime_checkable
class PageLabelRepository(Protocol):
    """Read/write access to the ``page_labels`` table."""

    def list_for_page(self, page_id: str) -> list[PageLabel]: ...
    def insert(self, label: PageLabel) -> PageLabel: ...
    def update(self, label: PageLabel) -> None: ...
    def delete(self, label_id: str) -> None: ...
    def delete_for_page(self, page_id: str) -> None: ...
    def copy_page(self, source_page_id: str, target_page_id: str) -> None: ...


@runtime_checkable
class ExportRepository(Protocol):
    """Read/write access to the ``export_history`` table."""

    def insert(
        self, project_id: str, output_path: str, page_count: int, quality: str
    ) -> ExportRecord: ...
    def list_for_project(self, project_id: str) -> list[ExportRecord]: ...


# ------------------------------------------------------------------- services


@runtime_checkable
class LayoutServiceProtocol(Protocol):
    """High-level page and item layout operations."""

    @property
    def project(self) -> Project: ...
    @property
    def db(self) -> object: ...

    def pages(self) -> list[PdfPage]: ...
    def page(self, page_id: str) -> PdfPage | None: ...
    def items(self, page_id: str) -> list[PageItem]: ...
    def all_items(self) -> list[PageItem]: ...
    def placed_document_ids(self) -> set[str]: ...
    def documents(self) -> dict[str, Document]: ...
    def library_counts(self) -> dict[str, int]: ...
    def item_counts(self) -> dict[str, int]: ...
    def add_page(
        self,
        *,
        paper_size: str | None = None,
        orientation: str | None = None,
        after_page_id: str | None = None,
        copy_from_page_id: str | None = None,
        margin_mm: float = 10.0,
    ) -> PdfPage: ...
    def delete_page(self, page_id: str) -> bool: ...
    def move_page(self, page_id: str, new_index: int) -> None: ...
    def duplicate_page(self, page_id: str) -> PdfPage | None: ...
    def update_page(self, page: PdfPage, **kwargs) -> PdfPage: ...
    def save_item(self, item: PageItem) -> None: ...
    def insert_items(self, items: list[PageItem]) -> None: ...
    def clear_page(self, page_id: str) -> None: ...


@runtime_checkable
class DocumentServiceProtocol(Protocol):
    """High-level document organisation operations."""

    def documents(self) -> list[Document]: ...
    def search(
        self,
        documents: list[Document],
        query: str = "",
        category_id: str | None = None,
        sort_by: str = "imported",
        descending: bool = False,
        only_missing: bool = False,
    ) -> list[Document]: ...
    def placed_count(self) -> int: ...
    def missing_documents(self) -> list[Document]: ...
    def validate_replacement(self, document: Document, candidate_path: str) -> object: ...
    def scan_folder_for_missing(
        self, folder: str, recursive: bool = True
    ) -> list[object]: ...
    def verify_hash(self, document: Document) -> bool | None: ...
    def category_names(self) -> dict[str | None, str]: ...


@runtime_checkable
class ProjectServiceProtocol(Protocol):
    """High-level project lifecycle operations."""

    def known_projects(self, limit: int | None = None) -> list: ...
    def recent_projects(self) -> list: ...
    def last_project(self) -> object | None: ...
    def create_project(self, *args, **kwargs) -> object: ...
    def open_project(self, db_path: str) -> object: ...
    def close_project(self, workspace: object) -> None: ...
    def save_project_as(self, workspace: object, target_folder: str) -> object: ...
    def rename_project(self, project_id: str, name: str) -> None: ...
    def delete_project(self, project_id: str) -> None: ...
    def project_summary(self, db_path: str) -> object: ...
